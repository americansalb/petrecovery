/**
 * The sample sentences a Script round shows.
 *
 * Server only, and that is a rule rather than a habit: if the browser
 * held the whole corpus it could match the text on screen against it and
 * read off the answer before the guess. The round endpoint sends one
 * sentence and a sealed token, the same way the panorama game sends a
 * panorama id and never the coordinate.
 *
 * **Two sources.** The first sentences in each list were written for the
 * game: a cold morning, hot tea, walking to work, the same few meanings
 * in every language so the content could not leak the answer. There
 * were two or three of them per language and that was the whole corpus,
 * which meant anybody who played twice had read all of it.
 *
 * The rest come from **Tatoeba** (CC-BY 2.0 FR), which this file named
 * as the upgrade it wanted before anybody had fetched it: real
 * sentences written by speakers, tagged with the same ISO 639-3 codes
 * the game uses. `scripts/build-script-corpus.js` fetches and filters
 * them, and the filtering is most of the work, because a crowdsourced
 * corpus is not a curated one:
 *
 * - every character has to be in the language's own script, so a
 *   transliteration filed under the wrong code cannot get in;
 * - no digits in any script, no currency, no URLs, no quotes;
 * - every word has to be among the commonest few hundred its language
 *   has, which strips names in scripts with no capital letters to spot
 *   them by, and strips the unusual vocabulary a crowdsourced corpus
 *   collects along with it;
 * - Tatoeba's stock cast, Tom and Mary and the rest, is named and
 *   refused: they are the commonest words in the corpus rather than
 *   rare ones, so frequency alone never catches them;
 * - nothing may name a place, a language or a number, checked against
 *   the same list __tests__/geo/script.test.js checks against;
 * - and it has to carry one of the language's own markers and none of
 *   a rival's, so every sentence still teaches something on the reveal
 *   and no sentence hands a feature to the wrong language.
 *
 * What survives all of that is 461 sentences across 75 languages, on
 * top of the 415 that were here. The other 84 keep what they had:
 * Tatoeba is thin in Wolof and Tetum, and a filter loose enough to find
 * something there would be loose enough to let a place name through
 * somewhere else.
 *
 * **A third source, from 2026-09-25: the Universal Declaration of Human
 * Rights.** It is translated into more languages than any other text,
 * and the Unicode UDHR project keeps the translations as plain text
 * (NLTK distributes that corpus as public domain). The languages added
 * that day take their sentences from it, copied exactly, and it has the
 * property the first sentences were written to have: every language says
 * the same things, so the content cannot give the answer away. A language
 * with no translation of the declaration has Tatoeba sentences instead,
 * picked one by one. Fifteen languages that still had two sentences each
 * (Thai, Amharic, Croatian, Tamil and others) got six or seven more the
 * same way, appended at the end of their lists, with markers written
 * for them.
 *
 * **The curation rule, which matters more than the size of the pool:**
 * strip proper nouns. A sentence containing a city name answers itself,
 * and so does a digit, a currency symbol or a flag. Nothing here names a
 * place, a person or a number, and __tests__/geo/script.test.js checks
 * that rather than trusting it.
 */

