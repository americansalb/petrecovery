// Generate postal codes for a range (e.g., '01' to '16' generates 01000-16999)
function generatePostalCodes(startPrefix, endPrefix, sampleCount = 50) {
  const codes = [];
  const start = parseInt(startPrefix, 10);
  const end = parseInt(endPrefix, 10);

  for (let prefix = start; prefix <= end; prefix++) {
    const prefixStr = prefix.toString().padStart(2, '0');
    // Generate sample postal codes for each prefix
    for (let i = 0; i < Math.min(sampleCount, 100); i++) {
      const suffix = (i * 10).toString().padStart(3, '0');
      codes.push(`${prefixStr}${suffix}`);
    }
  }
  return codes;
}

